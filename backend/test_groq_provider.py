@pytest.mark.asyncio
async def test_groq_successful_grounded_answer():
    """Verify Groq chat completion parsing, citation linking, and response structure."""
    passages = [
        {
            "document_id": "DOC-GROQ-01",
            "document_title": "IRC:112 Crack Standards",
            "chunk_index": 0,
            "content": "[Page 14] Maximum allowable design crack width is 0.20mm for moderate exposure.",
            "score": 0.92,
        }
    ]

    mock_chat_completion = MagicMock()
    mock_choice = MagicMock()
    mock_choice.message.content = "According to the IRC:112 specifications [DOC-1], the maximum design crack width is 0.20mm."
    mock_chat_completion.choices = [mock_choice]

    mock_client = MagicMock()
    mock_client.chat.completions.create = AsyncMock(return_value=mock_chat_completion)

    with patch.dict(os.environ, {"GROQ_API_KEY": "gsk_test_key_dummy_12345", "SITEWISE_AI_PROVIDER": "groq", "GROQ_MODEL": "openai/gpt-oss-120b"}):
        with patch("groq.AsyncGroq", return_value=mock_client):
            resp = await ai_provider._ask_groq("What is the crack limit?", passages)

            assert resp.provider == "groq"
            assert resp.model == "openai/gpt-oss-120b"
            assert resp.provider_available is True
            assert resp.is_grounded is True
            assert resp.insufficient_evidence is False
            assert len(resp.citations) == 1
            cit = resp.citations[0]
            assert cit.document_id == "DOC-GROQ-01"
            assert cit.document_title == "IRC:112 Crack Standards"
            assert cit.page_number == 14
            assert "0.20mm" in cit.excerpt


